"""The screen's art as C tables: app/art.h.
- the boot splash (app.c app_splash): assets/fm1-splash-dark.png, the nullwave mark and wordmark on black as the
  logotypes repository renders them for the FM-1, its lit box cut out (the version line is drawn by the firmware),
  in 16 colours, run-length coded: a byte is a colour (high nibble) and a run of 1..16 pixels (low nibble + 1)
- the knobs' ring (app.c knob): each pixel of a 19 x 19 box, its coverage of a ring 3 px thick at radius 9 that runs
  from 135 to 405 degrees (0 is right, clockwise on the screen), and where along the ring it lies, 0..255
  tools/gen_art.py [PNG]
"""
import math
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "assets" / "fm1-splash-dark.png"
OUT = ROOT / "app" / "art.h"


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def splash():
    im = Image.open(SRC).convert("RGB")
    w, h = im.size
    px = im.load()
    lit = lambda x, y: sum(px[x, y]) > 24
    rows = [y for y in range(h) if any(lit(x, y) for x in range(w))]
    # the version line at the foot is the firmware's: the art stops at the last gap of 16 rows or more
    top, bot = rows[0], rows[0]
    for y in rows[1:]:
        if y - bot > 16:
            break
        bot = y
    cols = [x for x in range(w) if any(lit(x, y) for y in range(top, bot + 1))]
    box = (cols[0] - 2, top - 2, cols[-1] + 3, bot + 3)
    art = im.crop(box)
    q = art.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:48]
    data = list(q.tobytes())
    bg = min(range(16), key=lambda i: sum(pal[3 * i:3 * i + 3]))
    out, i = [], 0
    while i < len(data):
        c, n = data[i], 1
        while i + n < len(data) and data[i + n] == c and n < 16:
            n += 1
        out.append(c << 4 | (n - 1))
        i += n
    colours = [rgb565(*pal[3 * k:3 * k + 3]) for k in range(16)]
    return box, art.size, colours, bg, out


def ring():
    R0, R1, N = 6.5, 9.5, 19
    cov, pos = [], []
    for y in range(N):
        for x in range(N):
            hit = 0
            for sy in range(4):
                for sx in range(4):
                    dx, dy = x + (sx + .5) / 4 - N / 2, y + (sy + .5) / 4 - N / 2
                    d = math.hypot(dx, dy)
                    a = (math.degrees(math.atan2(dy, dx)) - 135) % 360
                    hit += R0 <= d <= R1 and a <= 270
            cov.append(round(hit * 15 / 16))
            dx, dy = x + .5 - N / 2, y + .5 - N / 2
            a = (math.degrees(math.atan2(dy, dx)) - 135) % 360
            pos.append(min(255, round(a / 270 * 255)) if a <= 270 else 255)
    return N, cov, pos


def arr(name, ctype, vals, per=24):
    lines = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


box, size, colours, bg, rle = splash()
n, cov, pos = ring()
OUT.write_text(
    "/* SPDX-License-Identifier: MPL-2.0\n * Copyright (C) 2026 nullwave contributors */\n"
    "/* generated by tools/gen_art.py: the boot splash and the knobs' ring. Do not edit */\n#pragma once\n#include <stdint.h>\n\n"
    f"#define SPLASH_X {box[0]}\n#define SPLASH_Y {box[1]}\n#define SPLASH_W {size[0]}\n#define SPLASH_H {size[1]}\n"
    f"#define SPLASH_BG {bg}\n"
    + arr("SPLASH_PAL", "uint16_t", [f"0x{c:04X}u" for c in colours], 8)
    + arr("SPLASH_RLE", "uint8_t", rle)
    + f"\n#define RING_N {n}\n"
    + arr("RING_COV", "uint8_t", cov, n) + arr("RING_POS", "uint8_t", pos, n))
print(f"{OUT}: splash {size[0]}x{size[1]} at {box[:2]}, {len(rle)} bytes")

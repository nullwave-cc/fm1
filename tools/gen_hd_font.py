"""The screen's faces and its logo at 4x, for the host simulator's HD render (app/hd.c, NW_HD) only: the same Barlow
TTFs and roles as the device's (fm1-base's tools/gen_font.py, its "barlow" set), drawn at four times the size,
anti-aliased; and the logo's shapes (tools/gen_art.py's layout of the fm1 lockup), at 960 x 960.

    python3 tools/gen_hd_font.py OUT.h

Never in the firmware: the device keeps its own faces (app/build/gen/felucca_font.h).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "base" / "tools"))
import gen_font  # noqa: E402

SCALE = 4
FULL = ("L", "M", "B", "T")              # (fm1.toml font_full: lower case in these)


def logo(k=4):
    """the splash's shapes (tools/gen_art.py's layout of the fm1 lockup), each an 8-bit coverage mask in its box at
    960 x 960"""
    sys.path.insert(0, str(ROOT / "tools"))
    import gen_art
    out, boxes = [], []
    shapes = gen_art.splash_shapes()
    for j, (name, subs) in enumerate(shapes):
        cov = gen_art.shape_cover(subs, 960, k)
        bx = cov.getbbox()
        data = cov.crop(bx).tobytes()
        out.append(f"static const uint8_t HD_LOGO{j}[{len(data)}] = {{" + ",".join(map(str, data)) + "};")
        boxes.append(f"{{{bx[0]}, {bx[1]}, {bx[2] - bx[0]}, {bx[3] - bx[1]}, HD_LOGO{j}}}")
    out.append(f"static const struct {{ int32_t x, y, w, h; const uint8_t *a; }} HD_LOGO[{len(shapes)}] = {{"
               + ", ".join(boxes) + "};")
    return out


def main(out):
    lines = ["/* generated by tools/gen_hd_font.py: the screen's faces at 4x, host only (app/hd.c) */", "#pragma once",
             "#include <stdint.h>",
             "typedef struct { uint32_t h, first, last; const uint16_t *adv, *bw; const uint32_t *off; "
             "const uint8_t *data; } hd_font_t;", ""]
    for name, ttf, px, scale, pixel, first, last in gen_font.FONTSETS["barlow"]:
        last = 126 if name in FULL else last
        h, glyphs = gen_font.render(ttf, px * SCALE, 1, False, first, last)
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append(row[x] << 4 | row[x + 1])
        lines.append(f"static const uint8_t HD_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 32):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
        lines.append("};")
        lines.append(f"static const uint32_t HD_{name}_OFF[] = {{" + ",".join(map(str, offs)) + "};")
        lines.append(f"static const uint16_t HD_{name}_ADV[] = {{" + ",".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint16_t HD_{name}_BW[] = {{" + ",".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const hd_font_t HD_{name} = {{ {h}, {first}, {last}, HD_{name}_ADV, HD_{name}_BW, "
                     f"HD_{name}_OFF, HD_{name}_DATA }};")
        lines.append("")
    lines.append(f"#define HD_PAD {gen_font.PAD}")
    lines += logo()
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
